// Circular offsets match the captured canvas refresh behavior; fresh-session size is two.
export function getWelcomeSuggestionPage({ offset = 0, size = 2 } = {}) {
  return suggestionPage(homeFallbackZh, { offset, size });
}

export function getCanvasWelcomeSuggestionPage({ offset = 0, size = 2 } = {}) {
  return suggestionPage(canvasWelcomeSuggestions, { offset, size });
}

function suggestionPage(suggestions, { offset, size }) {
  if (!Number.isSafeInteger(offset)) throw new TypeError('Suggestion offset must be a safe integer');
  if (!Number.isSafeInteger(size) || size < 1 || size > suggestions.length) {
    throw new RangeError(`Suggestion size must be an integer from 1 to ${suggestions.length}`);
  }
  const total = suggestions.length;
  const current = ((offset % total) + total) % total;
  const items = Object.freeze(Array.from({ length: size }, (_, index) => suggestions[(current + index) % total]));
  return Object.freeze({ items, offset: current, nextOffset: (current + size) % total, size, total });
}

export function getWelcomeSuggestionCard(id) {
  const item = getWelcomeSuggestion(id);
  if (!item) return null;
  return Object.freeze({ ...item, description: null, icon: welcomeSuggestionIcons[item.icon_category].path });
}

// Adapt the original activation marker to the existing composer app reference without rewriting the raw prompt.
export function getWelcomeSuggestionInput(id) {
  const item = getWelcomeSuggestion(id);
  if (!item) return null;
  const marker = '{{brainstorm:brainstorm}} ';
  const brainstorm = item.prompt.startsWith(marker);
  const references = Object.freeze(brainstorm
    ? [Object.freeze({ kind: 'app', id: 'brainstorm', label: '头脑风暴' })]
    : []);
  return Object.freeze({
    prompt: item.prompt,
    text: brainstorm ? item.prompt.slice(marker.length) : item.prompt,
    references,
  });
}
