/** Return trusted static SVG; caller supplies the accessible label on its button. */
export function icon(name, { size = 20, strokeWidth = 2 } = {}) {
  const svg = icons[name];
  if (!svg) throw new RangeError(`Unknown Studio icon: ${name}`);
  if (!Number.isFinite(size) || size <= 0 || !Number.isFinite(strokeWidth) || strokeWidth <= 0) throw new RangeError("Invalid icon dimensions");
  return svg.replace(/width="20" height="20"/, `width="${size}" height="${size}"`).replace(/stroke-width="2"/, `stroke-width="${strokeWidth}"`);
}
